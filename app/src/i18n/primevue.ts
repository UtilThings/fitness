export function usePrimeVueLocale() {
  const { config } = usePrimeVue();
  const english = config.locale;
  if (!english) return;

  watch(
    locale,
    (value) => {
      config.locale =
        value === 'es'
          ? {
              ...english,
              ...spanish,
              aria: { ...english.aria, ...spanish.aria },
            }
          : english;
    },
    { immediate: true, flush: 'sync' },
  );
}
